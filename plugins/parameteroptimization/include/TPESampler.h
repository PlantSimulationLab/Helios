#ifndef TPESAMPLER_H
#define TPESAMPLER_H

#include <cstddef>
#include <random>
#include <vector>

namespace helios_tpe {

    //! Kind of search dimension handled by the sampler
    enum class DimensionKind {
        CONTINUOUS, //!< Real values in [low, high]
        INTEGER, //!< Integer values in [low, high] with a step of 1
        CATEGORICAL //!< Category indices in [0, n_choices)
    };

    //! One dimension of the search space
    struct SearchDimension {
        DimensionKind kind = DimensionKind::CONTINUOUS; //!< Kind of dimension
        double low = 0.0; //!< Lower bound (ignored for CATEGORICAL)
        double high = 0.0; //!< Upper bound (ignored for CATEGORICAL)
        size_t n_choices = 0; //!< Number of categories (ignored unless CATEGORICAL)
    };

    //! Mersenne Twister producing the same uniform stream as numpy.random.RandomState
    /** std::uniform_real_distribution differs between standard libraries, so the 53-bit conversion is written out here. */
    class UniformStream {
    public:
        explicit UniformStream(unsigned int seed);

        //! Next uniform value in [0, 1)
        double next();

    private:
        std::mt19937 engine_;
    };

    //! Standard normal CDF
    [[nodiscard]] double ndtr(double a);

    //! Natural log of the standard normal CDF
    [[nodiscard]] double logNdtr(double a);

    //! Natural log of the standard normal probability mass in [a, b]
    [[nodiscard]] double logGaussMass(double a, double b);

    //! Inverse of logNdtr: returns x such that y = logNdtr(x)
    [[nodiscard]] double ndtriExp(double y);

    //! Percent point function of the standard normal truncated to [a, b]
    /**
     * \param[in] q Quantile in [0, 1]
     * \param[in] a Lower truncation bound in standard units
     * \param[in] b Upper truncation bound in standard units
     */
    [[nodiscard]] double truncnormPpf(double q, double a, double b);

    //! Log density of a normal distribution truncated to standardized bounds [a, b]
    /**
     * \param[in] x Evaluation point
     * \param[in] a Lower truncation bound in standard units
     * \param[in] b Upper truncation bound in standard units
     * \param[in] loc Mean of the untruncated normal
     * \param[in] scale Standard deviation of the untruncated normal
     */
    [[nodiscard]] double truncnormLogPdf(double x, double a, double b, double loc, double scale);

    //! Indices that sort values, ordering ties as NumPy's generic np.argsort does
    /** Upstream orders tied observations this way wherever NumPy uses its generic quicksort. NumPy on x86 CPUs with AVX2 or
     *  AVX-512 instead uses a SIMD sort, which orders ties differently. It is not a stable sort, and tied INTEGER observations
     *  are common. Benchmarks with std::stable_sort, which ties the order of tied observations to their age, had a higher
     *  median regret on an INTEGER problem (see benchmarks/parameter_optimization).
     */
    [[nodiscard]] std::vector<size_t> numpyArgsort(const std::vector<double> &values);

    //! Number of trials assigned to the "below" (good) group out of n_trials finished trials
    [[nodiscard]] size_t defaultGamma(size_t n_trials);

    //! Kernel weights for n_observations observations in trial order, older observations weighing less beyond 25
    [[nodiscard]] std::vector<double> defaultWeights(size_t n_observations);

    //! Index of the candidate with the highest log-likelihood ratio, the first one on a tie
    /** A NaN ratio is never selected, whereas upstream's np.argmax would select it. If every ratio is NaN or -inf, returns 0. */
    [[nodiscard]] size_t selectBestCandidate(const std::vector<double> &log_likelihood_below, const std::vector<double> &log_likelihood_above);

    //! Mixture of product kernels fitted to a set of observations
    class ParzenEstimator {
    public:
        //! Fit the estimator
        /**
         * \param[in] observations One row per observation, in trial order, in internal representation
         * \param[in] dimensions Search space
         */
        ParzenEstimator(const std::vector<std::vector<double>> &observations, const std::vector<SearchDimension> &dimensions);

        //! Draw samples from the mixture, returning one row per sample
        [[nodiscard]] std::vector<std::vector<double>> sample(UniformStream &stream, size_t size) const;

        //! Evaluate the log density of the mixture at each row of samples
        [[nodiscard]] std::vector<double> logPdf(const std::vector<std::vector<double>> &samples) const;

        //! Normalized kernel weights; the last kernel is the prior
        [[nodiscard]] const std::vector<double> &getWeights() const {
            return weights_;
        }

        //! Kernel means of a numerical dimension (internal representation)
        [[nodiscard]] const std::vector<double> &getMus(size_t dimension) const {
            return kernels_.at(dimension).mu;
        }

        //! Kernel standard deviations of a numerical dimension
        [[nodiscard]] const std::vector<double> &getSigmas(size_t dimension) const {
            return kernels_.at(dimension).sigma;
        }

        //! Per-kernel category probabilities of a categorical dimension, one row per kernel
        [[nodiscard]] const std::vector<std::vector<double>> &getCategoricalWeights(size_t dimension) const {
            return kernels_.at(dimension).category_weights;
        }

    private:
        struct DimensionKernels {
            SearchDimension dimension;
            double adapted_low = 0.0; //!< Sampling lower bound (widened by half a step for INTEGER)
            double adapted_high = 0.0; //!< Sampling upper bound (widened by half a step for INTEGER)
            std::vector<double> mu;
            std::vector<double> sigma;
            std::vector<double> log_sigma;
            std::vector<double> truncation_a; //!< Standardized lower bound of each kernel
            std::vector<double> truncation_b; //!< Standardized upper bound of each kernel
            std::vector<double> log_mass; //!< Log probability mass of each kernel inside the bounds
            std::vector<std::vector<double>> category_weights;
            std::vector<std::vector<double>> log_category_weights;
        };

        void fitNumerical(DimensionKernels &kernels, const std::vector<std::vector<double>> &observations, size_t dimension_index) const;
        void fitCategorical(DimensionKernels &kernels, const std::vector<std::vector<double>> &observations, size_t dimension_index) const;

        std::vector<double> weights_;
        std::vector<double> weights_cdf_;
        std::vector<double> log_weights_;
        std::vector<DimensionKernels> kernels_;
    };

    //! Single-objective multivariate TPE sampler with a serial ask/tell interface
    class TPESampler {
    public:
        //! Create a sampler
        /**
         * \param[in] dimensions Search space
         * \param[in] n_startup_trials Number of initial trials sampled uniformly at random
         * \param[in] n_ei_candidates Number of candidates drawn from the "below" estimator per suggestion
         * \param[in] seed Seed of the random streams
         */
        TPESampler(std::vector<SearchDimension> dimensions, size_t n_startup_trials, size_t n_ei_candidates, unsigned int seed);

        //! Suggest the next point to evaluate, in internal representation
        [[nodiscard]] std::vector<double> ask();

        //! Report the objective value of an evaluated point
        void tell(const std::vector<double> &point, double value);

    private:
        [[nodiscard]] std::vector<double> sampleRandom();
        [[nodiscard]] std::vector<double> sampleModel();

        std::vector<SearchDimension> dimensions_;
        size_t n_startup_trials_;
        size_t n_ei_candidates_;
        UniformStream model_stream_;
        UniformStream random_stream_;
        std::vector<std::vector<double>> points_;
        std::vector<double> values_;
    };

} // namespace helios_tpe

#endif
